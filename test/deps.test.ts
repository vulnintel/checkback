import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import { buildSbom, lookupScope, readInventory } from "../src/index.js";
import { parsePnpmLock, parseRequirements } from "../src/deps/locks.js";
import { project } from "./helpers.js";

const fx = (p: string): string => readFileSync(new URL(`./fixtures/locks/${p}`, import.meta.url), "utf8");
const fixture = (dir: string, lock: string): Record<string, string> => ({ "package.json": fx(`${dir}/package.json`), [lock]: fx(`${dir}/${lock}`) });

const EXPECTED = [
  { name: "@sindresorhus/is", version: "4.6.0", dev: false, direct: true },
  { name: "is-number", version: "7.0.0", dev: false, direct: true },
  { name: "left-pad", version: "1.3.0", dev: true, direct: true },
];
const simple = (pkgs: { name: string; version: string | null; dev: boolean; direct: boolean }[]) =>
  pkgs.map(({ name, version, dev, direct }) => ({ name, version, dev, direct })).sort((a, b) => (a.name < b.name ? -1 : 1));

describe("AC21 lock parsers (real lockfiles generated by npm 10 / pnpm 8, 9, 11)", () => {
  it.each([
    ["npm-v1", "package-lock.json"],
    ["npm-v2", "package-lock.json"],
    ["npm-v3", "package-lock.json"],
    ["pnpm-v6.0", "pnpm-lock.yaml"],
    ["pnpm-v6.1", "pnpm-lock.yaml"],
    ["pnpm-v9.0", "pnpm-lock.yaml"],
  ])("%s: names, versions, dev, direct", async (dir, lock) => {
    const inv = await readInventory(project(fixture(dir, lock)));
    expect(inv.lockfiles).toHaveLength(1);
    expect(inv.lockfiles[0]).toMatchObject({ path: lock, status: "ok" });
    expect(simple(inv.lockfiles[0]!.packages)).toEqual(EXPECTED);
    expect(inv.lockfiles[0]!.packages.every((p) => p.origin === "registry" && p.integrity?.startsWith("sha512-"))).toBe(true);
  });

  it("pnpm 11 multi-document lockfile: main document + config dependency document", async () => {
    const inv = await readInventory(project(fixture("pnpm-v11-multidoc", "pnpm-lock.yaml")));
    const names = simple(inv.lockfiles[0]!.packages).map((p) => `${p.name}@${p.version}`);
    expect(names).toEqual(["@sindresorhus/is@4.6.0", "is-number@7.0.0", "is-odd@3.0.1", "left-pad@1.3.0"]);
  });

  it("pnpm 5.x asks to regenerate", () => {
    const r = parsePnpmLock("lockfileVersion: 5.4\npackages:\n  /lodash/4.17.21:\n    resolution: {integrity: sha512-x}\n");
    expect(r).toMatchObject({ status: "regenerate", packages: [] });
    expect(r.detail).toMatch(/pnpm 8/);
  });

  it("pnpm: peer suffixes, tarball (private), git/directory (local)", () => {
    const r = parsePnpmLock(`lockfileVersion: '9.0'
importers:
  .:
    dependencies:
      react-dom: {specifier: ^18, version: 18.2.0(react@18.2.0)}
      react: {specifier: ^18, version: 18.2.0}
      internal: {specifier: 'https://npm.acme.dev/internal-1.0.0.tgz', version: 'internal@https://npm.acme.dev/internal-1.0.0.tgz'}
packages:
  react@18.2.0:
    resolution: {integrity: sha512-a}
  react-dom@18.2.0:
    resolution: {integrity: sha512-b}
  internal@https://npm.acme.dev/internal-1.0.0.tgz:
    resolution: {tarball: https://npm.acme.dev/internal-1.0.0.tgz}
    version: 1.0.0
  mylib@git+https://github.com/a/b.git#abc:
    resolution: {type: git, repo: https://github.com/a/b.git, commit: abc}
    version: 0.1.0
snapshots:
  react@18.2.0: {}
  react-dom@18.2.0(react@18.2.0):
    dependencies:
      react: 18.2.0
`);
    expect(r.packages.map((p) => [p.name, p.version, p.origin, p.dev])).toEqual([
      ["react", "18.2.0", "registry", false],
      ["react-dom", "18.2.0", "registry", false],
      ["internal", "1.0.0", "private", false],
      ["mylib", "0.1.0", "local", true],
    ]);
  });

  it("requirements: == pins, -r inside CWD only, hashes/markers/extras ignored, names normalized", async () => {
    const dir = project({
      "requirements.txt": [
        "# comment",
        "-r requirements/base.txt",
        "-r ../outside.txt",
        "Django==4.2.7 \\",
        "    --hash=sha256:abc",
        "requests[socks]==2.31.0 ; python_version >= '3.8'",
        "Authlib>=1.0",
        "-e .",
        "git+https://github.com/a/b.git#egg=b",
        "pkg @ https://example.invalid/p.whl",
        "Zope.Interface==6.0",
      ].join("\n"),
      "requirements/base.txt": "fastapi==0.110.0\n",
    });
    const inv = await readInventory(dir);
    const lf = inv.lockfiles.find((l) => l.path === "requirements.txt")!;
    expect(lf.packages.map((p) => [p.name, p.version])).toEqual([
      ["fastapi", "0.110.0"],
      ["django", "4.2.7"],
      ["requests", "2.31.0"],
      ["authlib", null],
      ["zope-interface", "6.0"],
    ]);
  });

  it("requirements: -r cycle and absolute include are safe", () => {
    const files: Record<string, string> = { "a.txt": "-r b.txt\nx==1\n", "b.txt": "-r a.txt\n-r /etc/passwd\ny==2\n" };
    const r = parseRequirements(files["a.txt"]!, "a.txt", (rel) => files[rel] ?? null);
    expect(r.packages.map((p) => p.name)).toEqual(["y", "x"]);
  });

  it("unsupported lockfiles are listed for the 'next release' notice", async () => {
    const inv = await readInventory(project({ "yarn.lock": "", "bun.lockb": "", "poetry.lock": "", "web/Pipfile.lock": "{}" }));
    expect(inv.unsupported.map((u) => u.kind).sort()).toEqual(["bun-binary", "pipenv", "poetry", "yarn"]);
    expect(inv.lockfiles).toEqual([]);
  });

  it("AC22/AC23 (data side): lockfiles are per path; a package.json without a lock is a manifest with unpinned names", async () => {
    const dir = project({
      ...Object.fromEntries(Object.entries(fixture("npm-v3", "package-lock.json")).map(([k, v]) => [`apps/a/${k}`, v])),
      ...Object.fromEntries(Object.entries(fixture("pnpm-v9.0", "pnpm-lock.yaml")).map(([k, v]) => [`apps/b/${k}`, v])),
      "apps/c/package.json": JSON.stringify({ name: "c", dependencies: { express: "^4.19.0" } }),
    });
    const inv = await readInventory(dir);
    expect(inv.lockfiles.map((l) => l.path)).toEqual(["apps/a/package-lock.json", "apps/b/pnpm-lock.yaml"]);
    const t = lookupScope(inv).targets;
    expect(t.find((x) => x.name === "express")).toMatchObject({ version: null, sources: ["apps/c/package.json"] });
    expect(t.find((x) => x.name === "is-number")).toMatchObject({ version: "7.0.0", sources: ["apps/a/package-lock.json", "apps/b/pnpm-lock.yaml"] });
  });
});

describe("AC16 external lookup scope (§7-2) — data side; request interception is stage 4", () => {
  const app = (extra: Record<string, string> = {}): Record<string, string> => ({
    "package.json": JSON.stringify({
      name: "app",
      dependencies: { "@acme/ui": "^1.0.0", lodash: "^4.17.21", "made-up-pkg": "^1.0.0", shared: "workspace:*", local: "file:../local", gh: "github:a/b", alias: "npm:left-pad@^1", tools: "^2.0.0" },
    }),
    "package-lock.json": JSON.stringify({
      lockfileVersion: 3,
      packages: {
        "": { name: "app", dependencies: { "@acme/ui": "^1.0.0", lodash: "^4.17.21" } },
        "node_modules/@acme/ui": { version: "1.2.0", resolved: "https://registry.npmjs.org/@acme/ui/-/ui-1.2.0.tgz", integrity: "sha512-a" },
        "node_modules/lodash": { version: "4.17.21", resolved: "https://registry.npmjs.org/lodash/-/lodash-4.17.21.tgz", integrity: "sha512-b" },
        "node_modules/shared": { resolved: "packages/shared", link: true },
        "node_modules/priv": { version: "1.0.0", resolved: "https://npm.internal.example/priv/-/priv-1.0.0.tgz" },
      },
    }),
    "packages/shared/package.json": JSON.stringify({ name: "shared" }),
    "packages/tools/package.json": JSON.stringify({ name: "tools" }),
    ...extra,
  });
  const names = (s: ReturnType<typeof lookupScope>): string[] => s.targets.map((t) => `${t.ecosystem}:${t.name}@${t.version ?? "-"}`);

  it("(a) manifest-only names are targets; (e) workspace/file/git/link never are", async () => {
    const s = lookupScope(await readInventory(project(app())));
    expect(names(s)).toEqual(["npm:@acme/ui@1.2.0", "npm:left-pad@-", "npm:lodash@4.17.21", "npm:made-up-pkg@-"]);
    expect(s.excluded).toMatchObject({ local: 3, workspace: 1, private_registry: 1 });
  });

  it("(c) .npmrc scope registry excludes only that scope", async () => {
    const s = lookupScope(await readInventory(project(app({ ".npmrc": "@acme:registry=https://npm.acme.dev/\n" }))));
    expect(names(s)).not.toContain("npm:@acme/ui@1.2.0");
    expect(names(s)).toContain("npm:lodash@4.17.21");
    expect(s.excluded.private_scope).toBe(1);
  });

  it("(c) .yarnrc.yml npmScopes works the same", async () => {
    const s = lookupScope(await readInventory(project(app({ ".yarnrc.yml": "npmScopes:\n  acme:\n    npmRegistryServer: https://npm.acme.dev\n" }))));
    expect(names(s)).not.toContain("npm:@acme/ui@1.2.0");
  });

  it("(d) default registry changed → the whole npm ecosystem is excluded", async () => {
    const s = lookupScope(await readInventory(project(app({ ".npmrc": "registry=https://npm.acme.dev/\n" }))));
    expect(s.targets).toEqual([]);
    expect(s.privateEcosystems).toEqual(["npm"]);
  });

  it("(d) --extra-index-url / poetry / uv / Pipfile sources exclude PyPI", async () => {
    for (const files of [
      { "requirements.txt": "--extra-index-url https://pypi.acme.dev/simple\nrequests==2.31.0\n" },
      { "requirements.txt": "requests==2.31.0\n", "pyproject.toml": '[[tool.poetry.source]]\nname = "acme"\nurl = "https://pypi.acme.dev/simple"\n' },
      { "requirements.txt": "requests==2.31.0\n", "pyproject.toml": '[[tool.uv.index]]\nname = "acme"\nurl = "https://pypi.acme.dev/simple"\n' },
      { "requirements.txt": "requests==2.31.0\n", Pipfile: '[[source]]\nurl = "https://pypi.acme.dev/simple"\nname = "acme"\n' },
    ]) {
      const s = lookupScope(await readInventory(project(files)));
      expect(s.targets).toEqual([]);
      expect(s.privateEcosystems).toEqual(["PyPI"]);
    }
  });

  it("public PyPI index URL is not private", async () => {
    const s = lookupScope(await readInventory(project({ "requirements.txt": "-i https://pypi.org/simple\nrequests==2.31.0\n" })));
    expect(names(s)).toEqual(["PyPI:requests@2.31.0"]);
  });

  it("pyproject / Pipfile names without a lock are name-only targets", async () => {
    const s = lookupScope(
      await readInventory(
        project({
          "pyproject.toml": '[project]\ndependencies = ["FastAPI>=0.100", "my_lib[extra]"]\n[dependency-groups]\ndev = ["pytest"]\n',
          "svc/Pipfile": '[packages]\nflask = "*"\nlocalpkg = {path = "."}\n[dev-packages]\nblack = "*"\n',
        }),
      ),
    );
    expect(names(s)).toEqual(["PyPI:black@-", "PyPI:fastapi@-", "PyPI:flask@-", "PyPI:my-lib@-", "PyPI:pytest@-"]);
  });

  it("B7: same-repo packages are never looked up — uv workspace / path / git sources, project names, requirements file: refs, pnpm catalog aliases", async () => {
    const s = lookupScope(
      await readInventory(
        project({
          "api/pyproject.toml": [
            '[project]\nname = "dify-api"\ndependencies = ["flask>=3", "dify-vdb-pg", "Dify_Trace_X", "dify-agent", "flask-restx", "dify-sibling"]',
            '[tool.uv.workspace]\nmembers = ["providers/*"]',
            '[tool.uv.sources]\ndify-vdb-pg = { workspace = true }\ndify-agent = { path = "../dify-agent", editable = true }\nflask-restx = { git = "https://github.com/x/flask-restx" }\n',
          ].join("\n"),
          "api/providers/trace-x/pyproject.toml": '[project]\nname = "dify-trace-x"\ndependencies = ["requests"]\n',
          "sibling/pyproject.toml": '[project]\nname = "dify_sibling"\n',
          "tools/requirements.txt": "-e ./localpkg\nfile:../other\nrich==13.0.0\n",
          "pnpm-workspace.yaml": "packages: ['cli']\ncatalog:\n  '@typescript/native': npm:typescript@7.1.0-beta\n  vite: 6.0.0\ncatalogs:\n  legacy:\n    react: 17.0.2\n",
          "cli/package.json": JSON.stringify({ name: "cli", dependencies: { "@typescript/native": "catalog:", vite: "catalog:", react: "catalog:legacy" } }),
        }),
      ),
    );
    expect(names(s)).toEqual(["PyPI:flask@-", "PyPI:requests@-", "PyPI:rich@13.0.0", "npm:react@-", "npm:typescript@-", "npm:vite@-"]);
    expect(s.excluded).toMatchObject({ local: 3, workspace: 2 });
  });
});

describe("CycloneDX SBOM (§7-5, §8-3)", () => {
  const projectFiles = (): Record<string, string> => ({
    ...fixture("npm-v3", "package-lock.json"),
    "svc/requirements.txt": "Django==4.2.7\nrequests>=2\n",
    ".npmrc": "@acme:registry=https://npm.acme.dev/\n",
    "web/package-lock.json": JSON.stringify({
      lockfileVersion: 3,
      packages: {
        "": { name: "web", dependencies: { "@acme/ui": "1.0.0", "is-number": "7.0.0" } },
        "node_modules/@acme/ui": { version: "1.0.0", resolved: "https://npm.acme.dev/@acme/ui/-/ui-1.0.0.tgz", license: "UNLICENSED" },
        "node_modules/is-number": { version: "7.0.0", resolved: "https://registry.npmjs.org/is-number/-/is-number-7.0.0.tgz", license: "MIT" },
      },
    }),
  });

  it("AC31: same input → same bytes; no serialNumber / timestamp / project name", async () => {
    const dir = project(projectFiles());
    const a = buildSbom(await readInventory(dir), { forUpload: true });
    const b = buildSbom(await readInventory(dir), { forUpload: true });
    expect(a).toBe(b);
    expect(buildSbom(await readInventory(dir))).toBe(buildSbom(await readInventory(dir)));
    const j = JSON.parse(a);
    expect(j.serialNumber).toBeUndefined();
    expect(j.metadata?.timestamp).toBeUndefined();
    expect(j.metadata?.component).toBeUndefined();
  });

  it("AC35: specVersion ≥ 1.4, every component has a purl; export includes private, upload excludes it and lockfile names", async () => {
    const inv = await readInventory(project(projectFiles()));
    const exp = JSON.parse(buildSbom(inv));
    expect(Number(exp.specVersion.split(".")[1])).toBeGreaterThanOrEqual(4);
    const purls = exp.components.map((x: { purl: string }) => x.purl);
    expect(purls).toEqual([
      "pkg:npm/%40acme/ui@1.0.0",
      "pkg:npm/%40sindresorhus/is@4.6.0",
      "pkg:npm/is-number@7.0.0",
      "pkg:npm/left-pad@1.3.0",
      "pkg:pypi/django@4.2.7",
    ]);
    const isNum = exp.components.find((x: { name: string }) => x.name === "is-number");
    expect(isNum.properties.filter((p: { name: string }) => p.name === "checkback:lockfile").map((p: { value: string }) => p.value)).toEqual([
      "package-lock.json",
      "web/package-lock.json",
    ]);
    expect(exp.components.find((x: { name: string }) => x.name === "is").group).toBe("@sindresorhus");

    const up = buildSbom(inv, { forUpload: true });
    expect(up).not.toContain("acme");
    expect(up).not.toContain("checkback:lockfile");
    expect(up).not.toContain("package-lock");
    expect(JSON.parse(up).components).toHaveLength(4);
  });

  it("validates against the official CycloneDX 1.6 JSON schema", async () => {
    const { Validation, Spec } = await import("@cyclonedx/cyclonedx-library");
    const v = new Validation.JsonStrictValidator(Spec.Version.v1dot6);
    const inv = await readInventory(project(projectFiles()));
    expect(await v.validate(buildSbom(inv))).toBeNull();
    expect(await v.validate(buildSbom(inv, { forUpload: true }))).toBeNull();
  });
});
